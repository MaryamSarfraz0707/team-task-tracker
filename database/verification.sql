-- Team Task Tracker verification queries
-- Purpose: prove that schema.sql produced the expected structure, keys, and
-- relationships on a clean MySQL instance. This file changes no data.

USE TeamTaskTracker;

-- 1. Confirm tables and columns.
-- SHOW TABLES lists the three expected tables; DESCRIBE shows column types,
-- nullability, defaults, and generated behavior.
SHOW TABLES;
DESCRIBE Users;
DESCRIBE Tasks;
DESCRIBE TaskAuditLogs;

-- 2. Inspect foreign keys and indexes.
-- KEY_COLUMN_USAGE tells us which column points at which table/column.
-- Every row here is a real relationship enforced by MySQL, not by application code.
SELECT TABLE_NAME, CONSTRAINT_NAME, COLUMN_NAME, REFERENCED_TABLE_NAME,
       REFERENCED_COLUMN_NAME
FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE
WHERE TABLE_SCHEMA = DATABASE()
  AND REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY TABLE_NAME, CONSTRAINT_NAME;

-- 3. Confirm CHECK constraints exist.
-- These stop blank names/titles even if a client bypasses the API.
SELECT tc.TABLE_NAME, tc.CONSTRAINT_NAME, cc.CHECK_CLAUSE
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc
  ON cc.CONSTRAINT_SCHEMA = tc.CONSTRAINT_SCHEMA
 AND cc.CONSTRAINT_NAME = tc.CONSTRAINT_NAME
WHERE tc.CONSTRAINT_SCHEMA = DATABASE()
  AND tc.CONSTRAINT_TYPE = 'CHECK'
ORDER BY tc.TABLE_NAME, tc.CONSTRAINT_NAME;

-- 4. Confirm indexes used for list/filter and audit-history queries.
