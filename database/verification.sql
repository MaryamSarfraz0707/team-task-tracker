-- 7. Read tasks together with creator/editor identity.
SELECT t.TaskId, t.Title, t.Status, t.Priority, t.DueDate,
       creator.FullName AS CreatedBy,
       editor.FullName AS UpdatedBy,
       t.CreatedAtUtc, t.UpdatedAtUtc
FROM Tasks t
JOIN Users creator ON creator.UserId = t.CreatedByUserId
LEFT JOIN Users editor ON editor.UserId = t.UpdatedByUserId
ORDER BY t.TaskId DESC;

-- 8. Read audit history with actor.
SELECT a.AuditLogId, a.TaskId, u.FullName AS Actor, a.ActionType,
       a.ChangedFields, a.OldValues, a.NewValues, a.OccurredAtUtc
FROM TaskAuditLogs a
JOIN Users u ON u.UserId = a.ActorUserId
ORDER BY a.OccurredAtUtc DESC;
